// The ONE explicit classification of every route the API registers (tests/route-inventory.test.ts compares it with the
// real routes and fails on any route missing here or any entry without a route). Generated from the code once, reviewed by a
// human, and now maintained by hand: adding a route means adding a line here, on purpose.
//
//   public   no token needed (health, sign-in, the website API)
//   customer a customer token; a staff token is refused (401)
//   staff    a staff token whose role is in `roles`; a customer token is refused (401); other roles get 403
//   scoped   the route lets a role in, but only to the records assigned to that user (a 404 for anything else)
//   stream   a Server-Sent Events route: only the refusals are probed (an accepted request never ends)

